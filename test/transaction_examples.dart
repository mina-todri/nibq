/// 🔄 سيناريو حقيقي: خطأ أثناء الشراء يسبب Rollback تلقائي
void exampleRollbackOnError() {
  /*
  * الخطوات:
  * 
  * 1. العميل يحاول الشراء بمعلومات ناقصة:
  *    - معرف المستخدم غير متوفر (session انتهت)
  *    - أو عنوان التوصيل غير موجود
  *    - أو بيانات الدفع غير صحيحة
  *
  * 2. ما الذي يحدث:
  *    - Validation يكتشف المشكلة
  *    - Exception يُرفع
  *    - Transaction ينقطع فوراً
  *    - جميع التغييرات تلغى تلقائياً
  */

  print('''
═══════════════════════════════════════════════════════════════════════════════
🔄 مثال 4: Rollback تلقائي عند الخطأ
═══════════════════════════════════════════════════════════════════════════════

🛒 محتوى السلة:
  ├─ قهوة أرابيكا (الكمية: 5)
  ├─ تشيزكيك (الكمية: 2)
  └─ الإجمالي: 250 جنيه

📊 المخزون الحالي:
  ├─ القهوة: 100 قطعة ✓ (كافي)
  └─ التشيزكيك: 50 قطعة ✓ (كافي)

❌ المشكلة المكتشفة:
  userId = "" (فارغ - المستخدم لم يسجل دخول)

🔄 مراحل Firestore Transaction:
  [T1] قراءة المنتجات
       ✓ القهوة = 100
       ✓ التشيزكيك = 50

  [T2] التحقق من المخزون
       ✓ 100 >= 5 → نعم
       ✓ 50 >= 2 → نعم

  [T3] Validation - معرف المستخدم
       ❌ OrderModel.userId.isEmpty == true
       → رفع ArgumentError('Order has no userId')

  [T4] Transaction Rollback (تلقائي)
       ❌ لم نصل لكتابة الطلب (توقفنا في Validation)
       ❌ لم نصل لتحديث المخزون
       ❌ جميع التغييرات الموجودة لغت

  [T5] Return: ERROR

❌ النتيجة: ORDER NOT CREATED ✗

🛡️ الحماية:
  ✓ بطاقة المستخدم لم تُخصم (لم نصل لخادم الدفع)
  ✓ المخزون بقي كما هو:
    ├─ القهوة = 100 (لم ينقص)
    └─ التشيزكيك = 50 (لم ينقص)
  ✓ لا توجد عملية شراء في الدستة
  ✓ جدول الطلبات نظيف

📌 ملخص ACID:
  A - Atomicity: ✓ إما جميع التغييرات أو لا شيء
  C - Consistency: ✓ المخزون بقي متسقاً
  I - Isolation: ✓ لا تأثر بعمليات أخرى
  D - Durability: ✓ ما كُتب بقي محفوظاً

⚠️  رسالة الخطأ المعروضة:
    "حدث خطأ أثناء معالجة الطلب. يرجى تسجيل الدخول مرة أخرى"
═══════════════════════════════════════════════════════════════════════════════
  ''');
}

